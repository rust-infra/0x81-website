let currentLang: Language = (localStorage.getItem('moyan_lang') as Language) || 'zh-CN';

export function setLanguage(lang: Language) {
  currentLang = lang;
  localStorage.setItem('moyan_lang', lang);
  window.dispatchEvent(new CustomEvent('moyan:lang-change', { detail: lang }));
}

export function getLanguage(): Language {
  return currentLang;
}

export function t(key: string, params?: Record<string, string | number>): string {
  const set = translations[currentLang];
  let text = set[key] || translations['zh-CN'][key] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v));
    });
  }
  return text;
}
